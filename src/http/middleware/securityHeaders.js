// A small, readable set of response headers (instead of a header library).
//
// The Content-Security-Policy matters for this project in particular: the UI
// will display text that came from untrusted sources. If a rendering bug ever
// let that text become markup, the policy still stops it from loading remote
// images (a known data-exfiltration trick) or running inline script.
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

export function securityHeaders(_req, res, next) {
  res.setHeader('Content-Security-Policy', CSP);
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Referrer-Policy', 'no-referrer');
  res.setHeader('X-Frame-Options', 'DENY');
  next();
}
